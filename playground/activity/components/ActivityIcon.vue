function snap() {
  const svg = el.value
  if (!svg) return
  svg.style.transform = ''
  const r = svg.getBoundingClientRect()
  const dpr = window.devicePixelRatio || 1
  const dx = Math.round(r.left * dpr) / dpr - r.left
  const dy = Math.round(r.top * dpr) / dpr - r.top
  svg.style.transform = dx || dy ? `translate(${dx}px, ${dy}px)` : ''
}
